#!/usr/bin/env python3
# scripts/lock_requirements.py, writes requirements.lock from requirements.txt.
#
# Resolves requirements.txt in a fresh virtual environment, pins every package
# it installed to the exact version, and adds the sha256 of every file PyPI
# has for that version, so pip can install it on any platform with
# --require-hashes. Then runs pip-audit over the result.
#
# Needs the internet: it installs from PyPI and reads PyPI's JSON API.
#
#   python3 scripts/lock_requirements.py
#   pip install --require-hashes -r requirements.lock

import json
import pathlib
import subprocess
import sys
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIP = {"pip", "setuptools", "wheel"}


def run(argv):
    return subprocess.run(argv, check=True, capture_output=True, text=True).stdout


def hashes(name: str, version: str) -> list:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as resp:
        data = json.load(resp)
    found = sorted({f["digests"]["sha256"] for f in data.get("urls", [])})
    if not found:
        sys.exit(f"PyPI lists no files for {name}=={version}, refusing to "
                 f"write a lock that cannot be installed.")
    return found


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        py = pathlib.Path(tmp) / "bin" / "python"
        run([sys.executable, "-m", "venv", tmp])
        run([str(py), "-m", "pip", "install", "--quiet", "--upgrade", "pip"])
        run([str(py), "-m", "pip", "install", "--quiet",
             "-r", str(ROOT / "requirements.txt")])
        pins = []
        for line in run([str(py), "-m", "pip", "freeze", "--all"]).splitlines():
            name, sep, version = line.partition("==")
            if sep and name.lower() not in SKIP:
                pins.append((name, version))

        out = [f"# Generated by scripts/lock_requirements.py from requirements.txt,",
               f"# Python {sys.version_info.major}.{sys.version_info.minor}. "
               f"Do not edit, run the script again.", ""]
        for name, version in sorted(pins, key=lambda p: p[0].lower()):
            lines = [f"{name}=={version}"]
            lines += [f"    --hash=sha256:{h}" for h in hashes(name, version)]
            out.append(" \\\n".join(lines))
        lock = ROOT / "requirements.lock"
        lock.write_text("\n".join(out) + "\n", encoding="utf-8")
        print(f"Wrote {lock.name}: {len(pins)} packages, every one hashed.")

        run([str(py), "-m", "pip", "install", "--quiet", "pip-audit"])
        audit = subprocess.run([str(pathlib.Path(tmp) / "bin" / "pip-audit"),
                                "--require-hashes", "--disable-pip",
                                "-r", str(lock)], text=True)
        if audit.returncode:
            print("pip-audit found something above. Raise the floor in "
                  "requirements.txt and run this again.")
        return audit.returncode


if __name__ == "__main__":
    sys.exit(main())
